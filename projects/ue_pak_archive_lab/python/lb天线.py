def silent_patch_dir(target_dir: str, replacements: list[tuple[str, str]]) -> None:
    """静默就地替换，无备份、无打印"""
    dat_files = [os.path.join(target_dir, f) for f in os.listdir(target_dir) if f.lower().endswith(".dat")]
    for path in dat_files:
        with open(path, "r+b") as f:
            mm = mmap.mmap(f.fileno(), 0)
            try:
                for old_str, new_str in replacements:
                    old_bytes = old_str.encode("utf-8")
                    new_bytes = new_str.encode("utf-8")
                    if len(old_bytes) != len(new_bytes):
                        continue
                    pos = 0
                    while True:
                        pos = mm.find(old_bytes, pos)
                        if pos == -1:
                            break
                        mm[pos:pos+len(old_bytes)] = new_bytes
                        pos += len(old_bytes)
            finally:
                mm.close()

